  function auto(key) {
    if (!T[key]) return;
    cur = key;
    const seen = Store.d.howto || (Store.d.howto = {});
    if (seen[key]) return;
    seen[key] = 1; Store.save();
    const tryShow = (n = 0) => {
      if (Modal.isOpen) { if (n < 40) setTimeout(() => tryShow(n + 1), 500); return; }
      show(key);
    };
    setTimeout(tryShow, 250);
  }

  function forAct(act) { if (BY_ACT[act]) auto(BY_ACT[act]); }

  // Кнопка «?» во всех шапках игр
  function addButtons() {
    $$('.screen .topbar').forEach((bar) => {
      const id = bar.closest('.screen').id;
      if (id === 'profile' || id === 'pass-levels' || $('.help', bar)) return;
      const b = document.createElement('button');
      b.className = 'help'; b.textContent = '?'; b.setAttribute('aria-label', 'Как играть');
      b.addEventListener('click', () => show());
      bar.insertBefore(b, $('.coins', bar));
    });
  }

